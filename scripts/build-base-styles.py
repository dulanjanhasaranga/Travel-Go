#!/usr/bin/env python3
"""Flatten the base CSS import into a fingerprinted delivery file without changing rules."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
CSS=ROOT/'src/main/resources/static/css'
TEMPLATES=ROOT/'src/main/resources/templates'
MARKER='/* Generated by scripts/build-base-styles.py; edit style.css and transitions.css. */\n'
URL=re.compile(r'/css/(?:style\.css(?:\?v=[^"}\s]+)?|base-style\.[0-9a-f]{16}\.css)')

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    style=(CSS/'style.css').read_text(encoding='utf-8-sig').replace('\r\n','\n')
    transitions=(CSS/'transitions.css').read_text(encoding='utf-8-sig').replace('\r\n','\n')
    rule="@import url('./transitions.css');"
    if style.count(rule)!=1 or '@import' in style.replace(rule,'') or '@import' in transitions:
        raise SystemExit('Review base CSS imports before generating the delivery file.')
    content=(MARKER+'\n/* transitions.css */\n'+transitions+'\n/* style.css */\n'+style.replace(rule,'',1)).encode('utf-8')
    name='base-style.'+hashlib.sha256(content).hexdigest()[:16]+'.css';target=CSS/name
    stale=not target.exists() or target.read_bytes()!=content
    changed=0
    for file in TEMPLATES.rglob('*.html'):
        before=file.read_bytes();text=before.decode('utf-8')
        updated=re.sub(r'<link\b[^>]*>',lambda match:URL.sub('/css/'+name,match.group()),text)
        if updated!=text:
            stale=True;changed+=1
            if not args.check:file.write_bytes(updated.encode('utf-8'))
    if args.check and stale:raise SystemExit('Base styles are stale: run python scripts/build-base-styles.py')
    if not args.check:
        target.write_bytes(content)
        for old in CSS.glob('base-style.*.css'):
            if old!=target and old.read_text(encoding='utf-8').startswith(MARKER):old.unlink()
    print(('Verified ' if args.check else 'Built ')+name+f'; removed the nested stylesheet request; updated {changed} templates.')

if __name__=='__main__':main()
