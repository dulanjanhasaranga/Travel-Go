#!/usr/bin/env python3
"""Bundle the existing shared CSS in its reviewed cascade order, without rewriting rules.

No npm/runtime dependency is required. Sources remain editable; this checked-in delivery
asset must be regenerated before packaging. --check is a read-only CI/release check.
The content fingerprint changes the URL whenever any shared source changes.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
CSS = ROOT / "src/main/resources/static/css"
HEAD = ROOT / "src/main/resources/templates/fragments/site-head.html"
SOURCES = (
    "fonts.css", "navigation.css", "modern.css", "workspace-modern.css", "currency-estimates.css",
    "journey.css", "journey-catalogue.css", "journey-pages.css", "workspace-clear.css",
    "site-ui-clear.css", "status-refinement.css", "workspace-status-refinement.css",
    "project-blue-white.css", "brand-blue.css", "action-controls.css",
)
MARKER = "/* Generated by scripts/build-shared-css.py; edit the source CSS files. */\n"
REFERENCE = re.compile(r"/css/site-bundle\.(?:pending|[0-9a-f]{16})\.css")


def build() -> bytes:
    sections = [MARKER]
    for name in SOURCES:
        source = (CSS / name).read_text(encoding="utf-8-sig").replace("\r\n", "\n")
        # An import/charset in the middle of a bundle would change its semantics.
        if re.search(r"(?m)^\s*@(?:import|charset)\b", source):
            raise ValueError(f"{name}: resolve its import/charset before bundling")
        sections.append(f"\n/* Source: {name} */\n{source.rstrip()}\n")
    return "".join(sections).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the bundle or head reference is stale")
    args = parser.parse_args()
    content = build()
    name = f"site-bundle.{hashlib.sha256(content).hexdigest()[:16]}.css"
    destination = CSS / name
    head = HEAD.read_text(encoding="utf-8")
    matches = list(REFERENCE.finditer(head))
    if len(matches) != 1:
        raise ValueError("site-head must contain exactly one generated bundle reference")
    expected_head = REFERENCE.sub(f"/css/{name}", head)
    current = destination.exists() and destination.read_bytes() == content and head == expected_head
    if args.check and not current:
        print("Shared CSS is stale. Run: python scripts/build-shared-css.py", file=sys.stderr)
        return 1
    if not args.check:
        destination.write_bytes(content)
        HEAD.write_text(expected_head, encoding="utf-8", newline="\n")
        # Remove only this generator's obsolete output, never hand-authored CSS.
        for old in CSS.glob("site-bundle.*.css"):
            if old != destination and old.read_text(encoding="utf-8").startswith(MARKER):
                old.unlink()
    separate_gzip = sum(len(gzip.compress((CSS / x).read_bytes(), mtime=0)) for x in SOURCES)
    combined_gzip = len(gzip.compress(content, mtime=0))
    print(f"{'Verified' if args.check else 'Built'} {name}: {len(SOURCES)} requests -> 1; "
          f"{len(content):,} bytes; gzip {separate_gzip:,} -> {combined_gzip:,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
